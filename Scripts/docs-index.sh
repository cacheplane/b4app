#!/usr/bin/env bash
# The decision log and the verification record, one file per entry.
#
#   Scripts/docs-index.sh           write docs/decisions/index.md and
#                                   docs/verification/index.md (both gitignored)
#   Scripts/docs-index.sh --check   fail on a malformed file name or heading, a
#                                   decision number used twice, a number that
#                                   origin/main already holds under another
#                                   file, an entry appended to the old logs, or
#                                   a committed index
#   Scripts/docs-index.sh --next    print the next free decision number, after
#                                   the highest on origin/main, in this tree,
#                                   and in open pull requests (when gh works)
#
# Layout (D-174): docs/decisions/D-NNN-<slug>.md begins with the dated topic
# heading `## YYYY-MM-DD (topic)` and holds exactly one `- **D-NNN ...**`
# bullet; docs/verification/YYYY-MM-DD-<slug>.md begins with
# `## YYYY-MM-DD: <title>`. The indexes are generated and never committed, so
# two pull requests never edit the same line of the same file.
set -euo pipefail

root=$(cd "$(dirname "$0")/.." && pwd)
cd "$root"
decisions=docs/decisions
verification=docs/verification
export LC_ALL=C

fail=0
problem() {
  echo "docs-index: $*" >&2
  fail=1
}

# ---- reading entries -------------------------------------------------------

decision_files() {
  find "$decisions" -mindepth 1 -maxdepth 1 -name 'D-*.md' | sort
}

verification_files() {
  find "$verification" -mindepth 1 -maxdepth 1 -name '2*.md' | sort
}

# The decision's number from its file name: D-NNN.
number_of() {
  basename "$1" | sed -E 's/^(D-[0-9]{3}).*/\1/'
}

# The bold title of the one decision bullet in a file.
decision_title() {
  grep -E -m1 '^- \*\*D-[0-9]{3}' "$1" | sed -E 's/^- \*\*D-[0-9]{3}[a-z]? ?//; s/\*\*.*$//'
}

# The date and the topic (if any) from a decision file's first line.
decision_date() { head -n1 "$1" | sed -E 's/^## ([0-9-]{10}).*/\1/'; }
decision_topic() { head -n1 "$1" | sed -nE 's/^## [0-9-]{10} \((.*)\)$/\1/p'; }

verification_title() { head -n1 "$1" | sed -E 's/^## [0-9-]{10}: //'; }
verification_date() { head -n1 "$1" | sed -E 's/^## ([0-9-]{10}).*/\1/'; }

truncate_title() {
  local title=$1
  if [ "${#title}" -gt 160 ]; then
    printf '%s…' "${title:0:159}"
  else
    printf '%s' "$title"
  fi
}

# ---- generating ------------------------------------------------------------

write_indexes() {
  {
    echo "# Decision log, newest first"
    echo
    echo "Generated by \`Scripts/docs-index.sh\` from the files beside it; not committed. One line per decision."
    echo
    decision_files | sort -r | while read -r file; do
      printf -- '- [%s](%s) %s · %s\n' \
        "$(number_of "$file")" "$(basename "$file")" "$(decision_date "$file")" \
        "$(truncate_title "$(decision_title "$file")")"
    done
  } >"$decisions/index.md"
  {
    echo "# Verification record, newest first"
    echo
    echo "Generated by \`Scripts/docs-index.sh\` from the files beside it; not committed. One line per gate record."
    echo
    verification_files | sort -r | while read -r file; do
      printf -- '- [%s](%s) %s\n' \
        "$(verification_date "$file")" "$(basename "$file")" "$(verification_title "$file")"
    done
  } >"$verification/index.md"
  echo "wrote $decisions/index.md ($(decision_files | wc -l | tr -d ' ') decisions) and $verification/index.md ($(verification_files | wc -l | tr -d ' ') records)"
}

# ---- checking --------------------------------------------------------------

check_decisions() {
  local file name number count
  while read -r file; do
    problem "$file: only D-NNN-<slug>.md files belong in $decisions"
  done < <(find "$decisions" -mindepth 1 -maxdepth 1 ! -name 'D-*.md' ! -name index.md)
  for file in $(decision_files); do
    name=$(basename "$file")
    if ! echo "$name" | grep -qE '^D-[0-9]{3}-[a-z0-9]+(-[a-z0-9]+)*\.md$'; then
      problem "$name: the file name must be D-NNN-<slug>.md, the slug lowercase a-z, 0-9 and hyphens"
      continue
    fi
    number=$(number_of "$file")
    if ! head -n1 "$file" | grep -qE '^## [0-9]{4}-[0-9]{2}-[0-9]{2}( \(.+\))?$'; then
      problem "$name: the first line must be the dated topic heading, \`## YYYY-MM-DD (topic)\`"
    fi
    count=$(grep -cE '^- \*\*D-[0-9]{3}' "$file" || true)
    if [ "$count" -ne 1 ]; then
      problem "$name: holds $count top-level \`- **D-NNN\` bullets; one decision per file"
    elif ! grep -qE "^- \*\*$number\b" "$file"; then
      problem "$name: its decision bullet is $(grep -oE -m1 '^- \*\*D-[0-9]{3}' "$file" | cut -c5-), not $number"
    fi
  done
  while read -r number; do
    problem "$number is used by more than one file: $(find "$decisions" -name "$number-*.md" | sort | tr '\n' ' ')"
  done < <(for file in $(decision_files); do number_of "$file"; done | sort | uniq -d)
}

check_against_main() {
  local file name number theirs
  if ! git rev-parse --verify --quiet origin/main >/dev/null; then
    echo "docs-index: origin/main is not available here, so numbers were not checked against it (git fetch origin main)" >&2
    return
  fi
  for file in $(decision_files); do
    name=$(basename "$file")
    number=$(number_of "$file")
    theirs=$(git ls-tree --name-only origin/main "$decisions/" | grep -E "^$decisions/$number-" | sed 's|.*/||' || true)
    if [ -n "$theirs" ] && [ "$theirs" != "$name" ]; then
      problem "$number is taken on origin/main by $theirs; renumber $name (Scripts/docs-index.sh --next)"
    fi
  done
}

check_verification() {
  local file name date
  while read -r file; do
    problem "$file: only YYYY-MM-DD-<slug>.md files belong in $verification"
  done < <(find "$verification" -mindepth 1 -maxdepth 1 ! -name '2*.md' ! -name index.md)
  for file in $(verification_files); do
    name=$(basename "$file")
    if ! echo "$name" | grep -qE '^[0-9]{4}-[0-9]{2}-[0-9]{2}-[a-z0-9]+(-[a-z0-9]+)*\.md$'; then
      problem "$name: the file name must be YYYY-MM-DD-<slug>.md, the slug lowercase a-z, 0-9 and hyphens"
      continue
    fi
    date=${name:0:10}
    if ! head -n1 "$file" | grep -qE "^## $date: .+"; then
      problem "$name: the first line must be \`## $date: <title>\`"
    fi
  done
}

check_old_logs() {
  if grep -qE '^- \*\*D-[0-9]{3}|^## [0-9]{4}-[0-9]{2}-[0-9]{2}' docs/decisions.md; then
    problem "docs/decisions.md holds a decision entry; decisions go in $decisions/D-NNN-<slug>.md (AGENTS.md, \"Decisions and gate records\")"
  fi
  if grep -qE '^## [0-9]{4}-[0-9]{2}-[0-9]{2}' docs/verification.md; then
    problem "docs/verification.md holds a gate record; records go in $verification/YYYY-MM-DD-<slug>.md (AGENTS.md, \"Decisions and gate records\")"
  fi
  local index
  for index in "$decisions/index.md" "$verification/index.md"; do
    if git ls-files --error-unmatch "$index" >/dev/null 2>&1; then
      problem "$index is committed; the indexes are generated and gitignored"
    fi
  done
}

# ---- the next number -------------------------------------------------------

highest_number() {
  # Reads D-NNN tokens on stdin and prints the highest NNN as a decimal, or 0.
  local n
  n=$( (grep -oE 'D-[0-9]{3}' || true) | cut -c3- | sort -n | tail -n1)
  echo "$((10#${n:-0}))"
}

next_number() {
  local on_main in_tree in_prs highest
  on_main=$(git ls-tree --name-only origin/main "$decisions/" 2>/dev/null | highest_number)
  in_tree=$(decision_files | highest_number)
  in_prs=0
  if command -v gh >/dev/null 2>&1; then
    in_prs=$(gh pr list --state open --limit 100 --json files \
      --jq '.[].files[].path | select(startswith("docs/decisions/D-"))' 2>/dev/null | highest_number)
  fi
  highest=$on_main
  [ "$in_tree" -gt "$highest" ] && highest=$in_tree
  [ "$in_prs" -gt "$highest" ] && highest=$in_prs
  printf 'D-%03d\n' "$((highest + 1))"
  echo "(highest: origin/main D-$(printf '%03d' "$on_main"), this tree D-$(printf '%03d' "$in_tree"), open pull requests D-$(printf '%03d' "$in_prs"))" >&2
}

case "${1:-}" in
  "")
    write_indexes
    ;;
  --check)
    check_decisions
    check_against_main
    check_verification
    check_old_logs
    if [ "$fail" -ne 0 ]; then
      exit 1
    fi
    echo "docs-index: $(decision_files | wc -l | tr -d ' ') decisions and $(verification_files | wc -l | tr -d ' ') verification records are well formed"
    ;;
  --next)
    next_number
    ;;
  *)
    echo "usage: Scripts/docs-index.sh [--check | --next]" >&2
    exit 2
    ;;
esac
